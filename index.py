# Programme pour additionner deux nombres

# On demande à l'utilisateur d'entrer deux nombres
a = float(input("Entrez le premier nombre : "))
b = float(input("Entrez le deuxième nombre : "))

# On calcule la somme
somme = a + b

# On calcule la différence
difference = a - b

# On calcule le produit
produit = a * b

# On affiche le résultat
print("La somme de", a, "et", b, "est :", somme)
print("La différence de", a, "et", b, "est :", difference)
print("Le produit de", a, "et", b, "est :", produit)